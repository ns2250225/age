const sig = (x) => 1 / (1 + Math.exp(-x))
const round = (v) => Math.round(v * 1000) / 1000
const norm = (arr) => {
  const s = arr.reduce((a, b) => a + b, 0)
  return arr.map((v) => v / s)
}

function expModel(x, s, e, [lo, hi], pop, fame, aware, acc) {
  // 受经济条件影响的事物在各地普及时间不一，边界放宽
  const w = acc < 1 ? 3.2 : 2.5
  const inL = sig((x - (s - hi)) / w)
  const inR = sig((e - lo - x) / w)
  const ex = inL * inR
  const older = 1 - inL
  const younger = 1 - inR
  const has = ex * acc // 年龄对得上，而且接触得到
  const no = ex * (1 - acc) // 年龄对得上，但当地没有或家里没有
  const deep = pop * has
  const light = (1 - pop) * has * 0.65 + no * 0.3 + 0.2 * older * aware + 0.08 * younger * fame
  const heard = (1 - pop) * has * 0.35 + no * 0.5 + 0.6 * older * aware + 0.62 * younger * fame
  const never = no * 0.2 + older * (1 - aware) + younger * (1 - fame)
  return norm([deep, light, heard, never].map((v) => v + 0.02))
}

function table(fn) {
  // fn(year) -> number[]（每个选项的概率），返回每个选项一张 {year: p} 表
  const tables = []
  for (const y of YEARS) {
    fn(y).forEach((p, i) => {
      tables[i] ??= {}
      tables[i][String(y)] = round(p)
    })
  }
  return tables
}

const unknownOption = (text = '不知道 / 没印象') => ({ id: 'unknown', text, age_likelihood: null })
const LETTERS = ['a', 'b', 'c', 'd', 'e', 'f', 'g']
const decadeTag = (y) => `${Math.floor(y / 10) * 10}年代`
const tagList = (...groups) => [...new Set(groups.flatMap((g) => (Array.isArray(g) ? g : g.split(','))).filter(Boolean))]

const bank = Object.fromEntries(Object.keys(CATEGORIES).map((k) => [k, []]))
const nextId = (cat) => `${cat}_${String(bank[cat].length + 1).padStart(3, '0')}`

// ---- 经历/认识类（类型 A、B）----
// 行格式：[预设, 事物, 问题, 起始年, 结束年, 年龄窗口, 普及度, 后世知名度, 长辈知晓度, emoji, 附加?]
// 附加：标签字符串，或 { t: 标签, img: 配图, acc: 可及度 }
function addExp(cat, row) {
  const [preset, thing, question, s, e, winKey, pop, fame, aware, emoji, x = {}] = row
  const { t = '', img = '', acc = 1 } = typeof x === 'string' ? { t: x } : x
  const win = Array.isArray(winKey) ? winKey : WIN[winKey]
  if (!win) throw new Error(`未知的年龄窗口：${winKey}（${thing}）`)
  const p = PRESETS[preset]
  const tables = table((y) => expModel(y, s, e, win, pop, fame, aware, acc))
  const mid = Math.round((s + Math.min(e, s + 12)) / 2)
  const base = preset === 'witness' || preset === 'rec' || preset === 'say' ? 0.9 : 1
  bank[cat].push({
    id: nextId(cat),
    category: CATEGORIES[cat],
    type: preset === 'rec' ? 'recognition' : 'experience',
    question,
    thing,
    emoji,
    ...(img ? { image: `assets/questions/${img}.svg` } : {}),
    options: [
      ...p.opts.map((text, i) => ({
        id: LETTERS[i],
        text,
        level: 3 - i,
        statement: p.st[i].replace('X', thing),
        age_likelihood: tables[i],
      })),
      unknownOption(),
    ],
    era: { start: s, end: e },
    difficulty: pop >= 0.6 ? 1 : 2,
    weight: 1,
    // 受城乡/经济条件影响越大，可信度越低
    reliability: Math.round(base * (0.7 + 0.3 * acc) * 100) / 100,
    tags: tagList(decadeTag(mid), t),
    enabled: true,
  })
}

// ---- 多选一类（类型 C、D、E）----
// options: [text, 出生年下限, 出生年上限, 流行度?]
function addChoice(cat, type, topic, question, options, noneText, emoji, tags = '') {
  const w = 2.5
  const tables = table((y) =>
    norm([
      ...options.map(([, b1, b2, pop = 1]) => pop * sig((y - b1) / w) * sig((b2 - y) / w) + 0.02),
      0.1,
    ]),
  )
  bank[cat].push({
    id: nextId(cat),
    category: CATEGORIES[cat],
    type,
    question,
    thing: topic,
    emoji,
    options: [
      ...options.map(([text, b1, b2], i) => ({
        id: LETTERS[i],
        text,
        thing: text,
        level: 3,
        era: Math.round((b1 + b2) / 2) + 10,
        statement: `说到${topic}，你选的是「${text}」`,
        age_likelihood: tables[i],
      })),
      {
        id: LETTERS[options.length],
        text: noneText,
        level: 0,
        statement: `说到${topic}，这些选项你都没有印象`,
        age_likelihood: tables[options.length],
      },
      unknownOption(),
    ],
    difficulty: 1,
    weight: 1,
    reliability: 0.8,
    tags: tagList('多选', tags),
    enabled: true,
  })
}

// ---- 知识判断类（类型 F）：权重低，避免变成知识竞赛 ----
function addKnow(cat, thing, question, correct, wrongs, s, e, winKey, fame, aware, emoji) {
  const win = Array.isArray(winKey) ? winKey : WIN[winKey]
  const w = 2.5
  const pos = bank[cat].length % 3
  const texts = [...wrongs]
  texts.splice(pos, 0, correct)
  const tables = table((y) => {
    const inL = sig((y - (s - win[1])) / w)
    const inR = sig((e - win[0] - y) / w)
    const know = Math.min(1, inL * inR + (1 - inL) * aware + (1 - inR) * fame)
    const pc = 0.3 + 0.65 * know
    return texts.map((_, i) => (i === pos ? pc : (1 - pc) / wrongs.length))
  })
  bank[cat].push({
    id: nextId(cat),
    category: CATEGORIES[cat],
    type: 'knowledge',
    question,
    thing,
    emoji,
    options: [
      ...texts.map((text, i) => ({
        id: LETTERS[i],
        text,
        level: i === pos ? 1 : 0,
        statement: i === pos ? `你清楚「${thing}」是怎么回事` : `你对「${thing}」并不熟悉`,
        age_likelihood: tables[i],
      })),
      unknownOption(),
    ],
    era: { start: s, end: e },
    difficulty: 3,
    weight: 0.6,
    reliability: 0.6,
    tags: ['知识'],
    enabled: true,
  })
}

